def check_indicator_notes(entries, notes, root=ROOT):
    issues = []
    known = {row["id"] for row in entries}
    for indicator in sorted(set(notes) - known):
        issues.append(f"Orphan indicator note: {indicator}")
    for row in entries:
        note = notes.get(row["id"], {})
        for field in ("name", "summary"):
            if not isinstance(note.get(field), str) or not note[field].strip():
                issues.append(f"Missing indicator explanation: {row['id']}.{field}")
        if row["status"] != "available":
            if any(key in note for key in ("example", "symbol", "channel")):
                issues.append(f"Unavailable entry must not bind usage: {row['id']}")
            continue
        if note.get("channel") not in row["outputs"]:
            issues.append(f"Output association mismatch: {row['id']}")
        location = root / note.get("example", "")
        if not location.resolve().is_relative_to(root.resolve()) or not location.is_file():
            issues.append(f"Invalid example association: {row['id']}")
        else:
            tree = ast.parse(location.read_text())
            symbols = {
                node.name for node in tree.body if isinstance(node, (ast.FunctionDef, ast.ClassDef))
            }
            if note.get("symbol") not in symbols:
                issues.append(f"Invalid example symbol: {row['id']}")
    return issues


def indicator_usage(row, note):
    """Generated snippets are checked individually by documentation execution regressions; input data comes from the shared example."""
    name = row["id"].removeprefix("ta.")
    standard = {"open_": "Open", "high": "High", "low": "Low", "close": "Close", "volume": "Volume"}
    extra = {key: key for key in row["inputs"] if key not in standard}
    if row["inputs"] == ["close"]:
        arguments = "self.close"
    elif extra:
        mapping = {key: standard.get(key, key) for key in row["inputs"]}
        arguments = "inputs=" + repr(mapping)
    else:
        arguments = ""
    handle = "self.value" if len(row["outputs"]) == 1 else f"self.value.{note['channel']}"
    return (
        f"def init(self):\n    self.value = self.ta.{name}({arguments})\n"
        "    self.latest_value = None\n\n"
        f"def next(self):\n    channel = {handle}\n"
        "    if channel.valid[-1]:\n        self.latest_value = float(channel[-1])\n"
    )


def input_explanation(row):
    descriptions = {
        "benchmark": "benchmark is a lagged-price demonstration column; replace it with a real benchmark on the same calendar",
        "periods": "periods is a per-bar period; the example fixes it at 10",
        "fast": "fast is the three-bar mean of close prices",
        "slow": "slow is the ten-bar mean of close prices",
        "left": "left is the three-bar mean of close prices",
        "right": "right is the ten-bar mean of close prices",
        "condition": "condition indicates close above open",
        "trend": "trend indicates close above open",
        "signal": "signal is the percentage change in close",
        "anchor": "anchor marks every twentieth bar; replace it with actual period starts",
        "source": "source uses close prices",
    }
    extra = [descriptions[key] for key in row["inputs"] if key in descriptions]
    return "Example inputs: " + ("；".join(extra) if extra else "corresponding market-data columns from bundled GOOG") + "。"


def constraint_text(rule):
    labels = {"minimum": "Minimum", "maximum": "Maximum", "choices": "Allowed values"}
    parts = []
    for key, value in rule.items():
        if key not in {"kind", "default"}:
            parts.append(f"{labels.get(key, key)}：{code(value)}")
    return "；".join(parts) or "No additional constraints"


